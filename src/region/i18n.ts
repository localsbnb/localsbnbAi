export function t(locale: AppLocale | undefined, key: string, vars?: Record<string, string | number>): string {
  const row = MESSAGES[key];
  const loc = locale || FALLBACK;
  let text = row?.[loc] || row?.[FALLBACK] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

export function detailStateLabel(locale: AppLocale | undefined, state: unknown): string {
  const n = Number(state);
  if (Number.isFinite(n)) return t(locale, `state.detail.${n}`);
  return String(state ?? '-');
}

export function cleanStateLabel(locale: AppLocale | undefined, state: unknown): string {
  const n = Number(state);
  if (Number.isFinite(n)) {
    const label = t(locale, `clean.${n}`);
    if (label !== `clean.${n}`) return label;
  }
  return String(state ?? '-');
}
